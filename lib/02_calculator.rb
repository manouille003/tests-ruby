def add(value_one, value_two)
    value_one + value_two
end


def subtract(value_one, value_two)
    value_one - value_two
end


def sum (array)
    array.sum
end


def multiply(value_one,value_two)
    value_one * value_two
end


def power(value_one, value_two)
    value_one ** value_two
end


def factorial(value)
(value).times do |value * (value - 1)|
end
